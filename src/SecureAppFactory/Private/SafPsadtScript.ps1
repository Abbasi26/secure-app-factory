# Builds an Invoke-AppDeployToolkit.ps1 that calls the PSADT 4.1 public commands.
# The toolkit itself is not copied unless New-PsadtPackage -IncludeToolkit is set.

function Get-SafExitCodes {
    param($Manifest, [string]$Field, [int[]]$Default)

    $codes = Get-SafProp -Object $Manifest -Name @('psadt', $Field)
    if ($null -eq $codes) {
        return $Default
    }
    $values = New-Object System.Collections.Generic.List[int]
    foreach ($code in @($codes)) {
        $values.Add([int]$code)
    }
    return $values.ToArray()
}

function New-SafPsadtScriptText {
    param(
        [Parameter(Mandatory = $true)]
        $Manifest,
        [Parameter(Mandatory = $true)]
        $Tools
    )

    $vendor = Get-SafProp -Object $Manifest -Name @('psadt', 'appVendor')
    if ([string]::IsNullOrWhiteSpace([string]$vendor)) { $vendor = [string]$Manifest.publisher }
    $appName = Get-SafProp -Object $Manifest -Name @('psadt', 'appName')
    if ([string]::IsNullOrWhiteSpace([string]$appName)) { $appName = [string]$Manifest.name }
    $lang = Get-SafProp -Object $Manifest -Name @('psadt', 'appLang')
    if ([string]::IsNullOrWhiteSpace([string]$lang)) { $lang = 'EN' }
    $revision = Get-SafProp -Object $Manifest -Name @('psadt', 'appRevision')
    if ([string]::IsNullOrWhiteSpace([string]$revision)) { $revision = '01' }

    $success = Get-SafExitCodes -Manifest $Manifest -Field 'successExitCodes' -Default @(0)
    $reboot = Get-SafExitCodes -Manifest $Manifest -Field 'rebootExitCodes' -Default @(1641, 3010)
    $successText = '@(' + (($success | ForEach-Object { [string]$_ }) -join ', ') + ')'
    $rebootText = '@(' + (($reboot | ForEach-Object { [string]$_ }) -join ', ') + ')'

    $processLines = New-Object System.Collections.Generic.List[string]
    $processes = @(Get-SafProp -Object $Manifest -Name @('psadt', 'processesToClose'))
    $hasProcess = $false
    foreach ($process in $processes) {
        if ($null -eq $process) { continue }
        $hasProcess = $true
        $processName = [string](Get-SafProp -Object $process -Name @('name'))
        $description = [string](Get-SafProp -Object $process -Name @('description'))
        if ([string]::IsNullOrWhiteSpace($description)) { $description = $processName }
        $processLines.Add('        @{ Name = ' + (Format-SafSingleQuoted $processName) + '; Description = ' + (Format-SafSingleQuoted $description) + ' }')
    }
    $processText = '@()'
    if ($hasProcess) {
        $processText = "@(`n" + ($processLines -join ",`n") + "`n    )"
    }

    $fileName = [string]$Manifest.source.fileName
    $installArguments = [string]$Manifest.install.arguments
    $uninstallArguments = [string]$Manifest.uninstall.arguments
    $uninstallExpression = Format-SafRuntimePath -Path ([string]$Manifest.uninstall.filePath)
    $guid = [string]$Tools.psadt.moduleGuid
    $version = [string]$Tools.psadt.version

    $closeBlock = ''
    if ($hasProcess) {
        $closeBlock = @'
    if ($adtSession.AppProcessesToClose.Count -gt 0) {
        Show-ADTInstallationWelcome -CloseProcesses $adtSession.AppProcessesToClose -CloseProcessesCountdown 60
    }

'@
    }

    $script = @"
# Generated by Secure App Factory $($script:SafVersion).
# This deployment script is MIT licensed. When PSAppDeployToolkit is bundled beside it,
# that toolkit remains under the LGPL-3.0-or-later. See PACKAGE-NOTICE.txt.
# Deferrals are intentionally omitted so an Intune silent install does not wait on a user.

[CmdletBinding()]
param
(
    [Parameter(Mandatory = `$false)]
    [ValidateSet('Install', 'Uninstall', 'Repair')]
    [System.String]`$DeploymentType,

    [Parameter(Mandatory = `$false)]
    [ValidateSet('Auto', 'Interactive', 'NonInteractive', 'Silent')]
    [System.String]`$DeployMode,

    [Parameter(Mandatory = `$false)]
    [System.Management.Automation.SwitchParameter]`$SuppressRebootPassThru,

    [Parameter(Mandatory = `$false)]
    [System.Management.Automation.SwitchParameter]`$TerminalServerMode,

    [Parameter(Mandatory = `$false)]
    [System.Management.Automation.SwitchParameter]`$DisableLogging
)

`$adtSession = @{
    AppVendor = $(Format-SafSingleQuoted ([string]$vendor))
    AppName = $(Format-SafSingleQuoted ([string]$appName))
    AppVersion = $(Format-SafSingleQuoted ([string]$Manifest.version))
    AppArch = $(Format-SafSingleQuoted ([string]$Manifest.architecture))
    AppLang = $(Format-SafSingleQuoted ([string]$lang))
    AppRevision = $(Format-SafSingleQuoted ([string]$revision))
    AppSuccessExitCodes = $successText
    AppRebootExitCodes = $rebootText
    AppProcessesToClose = $processText
    AppScriptVersion = '1.0.0'
    AppScriptDate = '$((Get-Date).ToUniversalTime().ToString('yyyy-MM-dd'))'
    AppScriptAuthor = 'Secure App Factory'
    RequireAdmin = `$true
    DeployAppScriptFriendlyName = `$MyInvocation.MyCommand.Name
    DeployAppScriptParameters = `$PSBoundParameters
    DeployAppScriptVersion = $(Format-SafSingleQuoted $version)
}

function Install-ADTDeployment {
    [CmdletBinding()]
    param()

    `$adtSession.InstallPhase = "Pre-`$(`$adtSession.DeploymentType)"
$closeBlock    Show-ADTInstallationProgress
    `$adtSession.InstallPhase = `$adtSession.DeploymentType
    `$installerPath = Join-Path -Path `$adtSession.DirFiles -ChildPath $(Format-SafSingleQuoted $fileName)
    Start-ADTProcess -FilePath `$installerPath -ArgumentList $(Format-SafSingleQuoted $installArguments)
    `$adtSession.InstallPhase = "Post-`$(`$adtSession.DeploymentType)"
}

function Uninstall-ADTDeployment {
    [CmdletBinding()]
    param()

    `$adtSession.InstallPhase = "Pre-`$(`$adtSession.DeploymentType)"
$closeBlock    Show-ADTInstallationProgress
    `$adtSession.InstallPhase = `$adtSession.DeploymentType
    `$uninstallPath = $uninstallExpression
    Start-ADTProcess -FilePath `$uninstallPath -ArgumentList $(Format-SafSingleQuoted $uninstallArguments)
    `$adtSession.InstallPhase = "Post-`$(`$adtSession.DeploymentType)"
}

function Repair-ADTDeployment {
    [CmdletBinding()]
    param()

    `$adtSession.InstallPhase = 'Repair'
    `$installerPath = Join-Path -Path `$adtSession.DirFiles -ChildPath $(Format-SafSingleQuoted $fileName)
    Start-ADTProcess -FilePath `$installerPath -ArgumentList $(Format-SafSingleQuoted $installArguments)
}

`$ErrorActionPreference = [System.Management.Automation.ActionPreference]::Stop
`$ProgressPreference = [System.Management.Automation.ActionPreference]::SilentlyContinue
Set-StrictMode -Version 1

try {
    if (Test-Path -LiteralPath "`$PSScriptRoot\PSAppDeployToolkit\PSAppDeployToolkit.psd1" -PathType Leaf) {
        Get-ChildItem -LiteralPath "`$PSScriptRoot\PSAppDeployToolkit" -Recurse -File | Unblock-File -ErrorAction Ignore
        Import-Module -FullyQualifiedName @{
            ModuleName = "`$PSScriptRoot\PSAppDeployToolkit\PSAppDeployToolkit.psd1"
            Guid = '$guid'
            ModuleVersion = '$version'
        } -Force
    }
    else {
        Import-Module -Name PSAppDeployToolkit -MinimumVersion '$version' -Force
    }

    `$iadtParams = Get-ADTBoundParametersAndDefaultValues -Invocation `$MyInvocation
    `$adtSession = Remove-ADTHashtableNullOrEmptyValues -Hashtable `$adtSession
    `$adtSession = Open-ADTSession @adtSession @iadtParams -PassThru
}
catch {
    `$Host.UI.WriteErrorLine((Out-String -InputObject `$_ -Width ([System.Int32]::MaxValue)))
    exit 60008
}

try {
    Get-ChildItem -LiteralPath `$PSScriptRoot -Directory | & {
        process {
            if (`$_.Name -match '^PSAppDeployToolkit\..+`$') {
                Get-ChildItem -LiteralPath `$_.FullName -Recurse -File | Unblock-File -ErrorAction Ignore
                Import-Module -Name `$_.FullName -Force
            }
        }
    }
    & "`$(`$adtSession.DeploymentType)-ADTDeployment"
    Close-ADTSession
}
catch {
    `$mainErrorMessage = "Unhandled error in [`$(`$MyInvocation.MyCommand.Name)]. `$(Resolve-ADTErrorRecord -ErrorRecord `$_)"
    Write-ADTLogEntry -Message `$mainErrorMessage -Severity 3
    Close-ADTSession -ExitCode 60001
}
"@

    return $script
}
