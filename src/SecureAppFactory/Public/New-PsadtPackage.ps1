function New-PsadtPackage {
    <#
    .SYNOPSIS
        Builds a PSAppDeployToolkit v4 folder around a verified installer.

    .DESCRIPTION
        Without -IncludeToolkit the folder contains the generated deployment script, the installer, and a notice.
        With -IncludeToolkit the pinned upstream template zip is downloaded, its hash is checked, and it is extracted.
        The toolkit is LGPL-3.0-or-later and is not stored in this repository.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string]$InstallerPath,
        [Parameter(Mandatory = $true)]
        $Manifest,
        [Parameter(Mandatory = $true)]
        [string]$Destination,
        [switch]$IncludeToolkit,
        [string]$ToolCache,
        [scriptblock]$WebClient
    )

    if (-not (Test-Path -LiteralPath $InstallerPath)) {
        throw "Installer not found: $InstallerPath"
    }
    $tools = Get-SafExternalTools
    if (-not $ToolCache) {
        $ToolCache = Join-Path ([System.IO.Path]::GetTempPath()) 'secure-app-factory'
    }
    if (-not (Test-Path -LiteralPath $Destination)) {
        New-Item -ItemType Directory -Path $Destination -Force | Out-Null
    }

    $bundled = $false
    if ($IncludeToolkit) {
        $zipPath = Join-Path $ToolCache ("PSAppDeployToolkit_Template_v{0}.zip" -f $tools.psadt.version)
        $expected = ([string]$tools.psadt.sha256).ToLowerInvariant()
        $needsDownload = $true
        if (Test-Path -LiteralPath $zipPath) {
            $needsDownload = (Get-SafSha256 -Path $zipPath) -ne $expected
        }
        if ($needsDownload) {
            Invoke-SafDownloadFile -Uri ([string]$tools.psadt.url) -Destination $zipPath -WebClient $WebClient
            $observed = Get-SafSha256 -Path $zipPath
            if ($observed -ne $expected) {
                Remove-Item -LiteralPath $zipPath -Force
                throw "PSAppDeployToolkit template hash mismatch. Expected $expected. Observed $observed."
            }
        }
        Expand-SafZip -ZipPath $zipPath -Destination $Destination
        $bundled = $true
        foreach ($placeholder in @(
            'Files/Add Setup Files Here.txt',
            'SupportFiles/Add Supporting Files Here.txt'
        )) {
            $placeholderPath = Join-Path $Destination $placeholder
            if (Test-Path -LiteralPath $placeholderPath) {
                Remove-Item -LiteralPath $placeholderPath -Force
            }
        }
    }
    else {
        foreach ($folder in @('Files', 'SupportFiles')) {
            $folderPath = Join-Path $Destination $folder
            if (-not (Test-Path -LiteralPath $folderPath)) {
                New-Item -ItemType Directory -Path $folderPath -Force | Out-Null
            }
        }
    }

    $fileName = [string]$Manifest.source.fileName
    $copied = Join-Path (Join-Path $Destination 'Files') $fileName
    Copy-Item -LiteralPath $InstallerPath -Destination $copied -Force
    $scriptPath = Join-Path $Destination 'Invoke-AppDeployToolkit.ps1'
    $scriptText = New-SafPsadtScriptText -Manifest $Manifest -Tools $tools
    Write-SafTextFile -Path $scriptPath -Text $scriptText

    $notice = @"
Secure App Factory $($script:SafVersion) package notice
=======================================================

Invoke-AppDeployToolkit.ps1 was generated by Secure App Factory and is covered by the MIT license of that project.

"@
    if ($bundled) {
        $notice += @"
This folder also contains PSAppDeployToolkit $($tools.psadt.version), which is licensed under the GNU LGPL-3.0-or-later.
The upstream license file is PSAppDeployToolkit/COPYING.Lesser. Do not remove it.
The toolkit files under PSAppDeployToolkit/ were extracted from the pinned upstream template and were not modified.
Distributing this combined folder means you must comply with that LGPL for the toolkit portion.

"@
    }
    else {
        $notice += @"
PSAppDeployToolkit is not bundled in this folder.
Rebuild with -IncludeToolkit to download the pinned template, or install PSAppDeployToolkit $($tools.psadt.version) on the deployment machine.
The generated script imports the bundled copy when it is present, and otherwise imports the installed module.

"@
    }
    Write-SafTextFile -Path (Join-Path $Destination 'PACKAGE-NOTICE.txt') -Text $notice

    return [pscustomobject]@{
        Created         = $true
        Path            = (Resolve-Path -LiteralPath $Destination).Path
        ScriptPath      = $scriptPath
        InstallerPath   = $copied
        ToolkitBundled  = $bundled
        ToolkitVersion  = [string]$tools.psadt.version
    }
}
