function Format-SafCell {
    param([AllowEmptyString()][string]$Value)
    if ($null -eq $Value) { return '' }
    return (($Value -replace '\|', '/') -replace '\r?\n', ' ')
}

function New-PackageReport {
    <#
    .SYNOPSIS
        Writes the Markdown package report for one build.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        $Result,
        [Parameter(Mandatory = $true)]
        [string]$Path
    )

    $name = [string](Get-SafProp -Object $Result -Name @('App', 'Name'))
    $version = [string](Get-SafProp -Object $Result -Name @('App', 'Version'))
    $demo = [bool](Get-SafProp -Object $Result -Name @('Demo'))
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("# Package report: $name $version")
    $lines.Add('')
    $lines.Add("Generated by Secure App Factory $([string](Get-SafProp -Object $Result -Name @('ModuleVersion'))).")
    if ($demo) {
        $lines.Add('Demo mode: downloads, Authenticode, the smoke test, tool downloads, and Intune upload were not performed.')
    }
    else {
        $lines.Add('This report is local. It is not a SLSA attestation.')
    }
    $lines.Add('')

    $errorText = [string](Get-SafProp -Object $Result -Name @('Error'))
    if (-not [string]::IsNullOrWhiteSpace($errorText)) {
        $lines.Add('## Result')
        $lines.Add('')
        $lines.Add('The build stopped.')
        $lines.Add('')
        $lines.Add('- ' + (Format-SafCell $errorText))
        $lines.Add('')
    }

    $trust = Get-SafProp -Object $Result -Name @('Trust')
    if ($null -ne $trust) {
        $lines.Add('## Trust')
        $lines.Add('')
        $lines.Add('| Check | Result | Detail |')
        $lines.Add('| --- | --- | --- |')
        $hashMatch = [bool](Get-SafProp -Object $trust -Name @('Hash', 'Match'))
        $hashResult = $(if ($hashMatch) { 'Pass' } else { 'Fail' })
        $hashDetail = "source $(Get-SafProp -Object $trust -Name @('Hash','Source')); expected $(Get-SafProp -Object $trust -Name @('Hash','Expected')); observed $(Get-SafProp -Object $trust -Name @('Hash','Actual'))"
        $lines.Add(('| SHA-256 | {0} | {1} |' -f $hashResult, (Format-SafCell $hashDetail)))
        $pin = Get-SafProp -Object $trust -Name @('ProductionPin')
        if ($null -ne $pin) {
            $agree = [bool](Get-SafProp -Object $pin -Name @('AgreesWithLock'))
            $pinLabel = $(if ($agree) { 'Agree' } else { 'Disagree' })
            $pinDetail = Format-SafCell ("manifest $(Get-SafProp -Object $pin -Name @('Value')); lock $(Get-SafProp -Object $pin -Name @('LockValue'))")
            $lines.Add(('| Manifest pin and lock | {0} | {1} |' -f $pinLabel, $pinDetail))
        }
        $signature = Get-SafProp -Object $trust -Name @('Signature')
        $sigMatch = [bool](Get-SafProp -Object $signature -Name @('Match'))
        $sigLabel = $(if ($sigMatch) { 'Pass' } else { 'Fail' })
        if ([bool](Get-SafProp -Object $signature -Name @('Mock'))) {
            $sigLabel = "$sigLabel (mock)"
        }
        $sigDetail = "status $(Get-SafProp -Object $signature -Name @('Status')); subject $(Get-SafProp -Object $signature -Name @('Subject')); thumbprint $(Get-SafProp -Object $signature -Name @('Thumbprint')); platform $(Get-SafProp -Object $signature -Name @('Platform'))"
        $lines.Add(('| Authenticode | {0} | {1} |' -f $sigLabel, (Format-SafCell $sigDetail)))
        $lines.Add('')
        $reasons = @(Get-SafProp -Object $trust -Name @('Reasons'))
        if ($reasons.Count -gt 0 -and -not [string]::IsNullOrWhiteSpace([string]$reasons[0])) {
            $lines.Add('Notes:')
            $lines.Add('')
            foreach ($reason in $reasons) {
                if (-not [string]::IsNullOrWhiteSpace([string]$reason)) {
                    $lines.Add('- ' + (Format-SafCell ([string]$reason)))
                }
            }
            $lines.Add('')
        }
    }

    $lines.Add('## Package')
    $lines.Add('')
    $lines.Add('| Artifact | Result | Detail |')
    $lines.Add('| --- | --- | --- |')
    $psadt = Get-SafProp -Object $Result -Name @('Psadt')
    if ($null -eq $psadt) {
        $lines.Add('| PSADT folder | Not created | The build stopped before packaging. |')
    }
    else {
        $bundled = [bool](Get-SafProp -Object $psadt -Name @('ToolkitBundled'))
        $lines.Add('| PSADT folder | Created | toolkit bundled: {0} |' -f ($(if ($bundled) { 'yes' } else { 'no' })))
    }
    $intuneWin = Get-SafProp -Object $Result -Name @('IntuneWin')
    if ($null -eq $intuneWin) {
        $lines.Add('| .intunewin | Not created | |')
    }
    else {
        $winStatus = Format-SafCell ([string](Get-SafProp -Object $intuneWin -Name @('Status')))
        $winReason = Format-SafCell ([string](Get-SafProp -Object $intuneWin -Name @('Reason')))
        $lines.Add(('| .intunewin | {0} | {1} |' -f $winStatus, $winReason))
    }
    $sbom = Get-SafProp -Object $Result -Name @('Sbom')
    if ($null -ne $sbom) {
        $sbomVersion = Format-SafCell ([string](Get-SafProp -Object $sbom -Name @('SpecVersion')))
        $sbomFile = Format-SafCell (Split-Path -Leaf ([string](Get-SafProp -Object $sbom -Name @('Path'))))
        $lines.Add(('| SBOM | CycloneDX {0} | {1} |' -f $sbomVersion, $sbomFile))
    }
    $provenance = Get-SafProp -Object $Result -Name @('Provenance')
    if ($null -ne $provenance) {
        $lines.Add('| Provenance | Local record | {0} |' -f (Format-SafCell ([string](Get-SafProp -Object $provenance -Name @('Schema')))))
    }
    $lines.Add('')

    $smoke = Get-SafProp -Object $Result -Name @('SmokeTest')
    $lines.Add('## Smoke test')
    $lines.Add('')
    if ($null -eq $smoke) {
        $lines.Add('Not run.')
    }
    else {
        $lines.Add("- Status: $([string](Get-SafProp -Object $smoke -Name @('Status')))")
        $lines.Add("- Mode: $([string](Get-SafProp -Object $smoke -Name @('Mode')))")
        $lines.Add("- Install: $(Format-SafCell ([string](Get-SafProp -Object $smoke -Name @('InstallCommand'))))")
        $lines.Add("- Uninstall: $(Format-SafCell ([string](Get-SafProp -Object $smoke -Name @('UninstallCommand'))))")
        $lines.Add("- Detection: $(Format-SafCell ([string](Get-SafProp -Object $smoke -Name @('Detection'))))")
        $lines.Add("- $($([string](Get-SafProp -Object $smoke -Name @('Reason'))))")
    }
    $lines.Add('')

    $upload = Get-SafProp -Object $Result -Name @('Upload')
    $lines.Add('## Intune upload')
    $lines.Add('')
    if ($null -eq $upload) {
        $lines.Add('Not considered.')
    }
    else {
        $lines.Add("- Status: $([string](Get-SafProp -Object $upload -Name @('Status')))")
        $lines.Add("- $($([string](Get-SafProp -Object $upload -Name @('Reason'))))")
        $lines.Add('- v0.1 does not create an assignment.')
    }
    $lines.Add('')

    $text = $lines -join "`n"
    Write-SafTextFile -Path $Path -Text $text
    return $text
}
